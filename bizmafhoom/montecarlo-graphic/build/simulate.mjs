// Build step: run the GBM Monte Carlo and freeze everything the composition shows.
//   node build/simulate.mjs
// Writes assets/sim-data.js (window.MC_SIM, loaded by index.html) and assets/sim.json
// (human-auditable summary). Every number on screen is read from MC_SIM.
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const gbm = require("../../kit/lib/gbm.js");

const here = dirname(fileURLToPath(import.meta.url));
const assets = join(here, "..", "assets");

export const PARAMS = {
  S0: 100,
  mu: 0.08,
  sigma: 0.25,
  steps: 252,
  years: 1,
  nRuns: 1000, // histogram, mean, VaR
  nVisible: 200, // drawn paths = the first 200 of the same 1000 runs
  seed: 20260924,
};

export const HIST = { min: 40, max: 200, binWidth: 8 };

const paths = gbm.simulate({ ...PARAMS, nPaths: PARAMS.nRuns });
const terminals = paths.map((p) => p[p.length - 1]);

const mean = gbm.mean(terminals);
const p5 = gbm.percentile(terminals, 5);
const median = gbm.percentile(terminals, 50);
const var95 = PARAMS.S0 - p5; // absolute 1-year VaR vs. today's value
const hist = gbm.histogram(terminals, { ...HIST, clamp: true });
const probLoss = terminals.filter((t) => t < PARAMS.S0).length / terminals.length;

const round2 = (v) => Math.round(v * 100) / 100;
const fmt1 = (v) => (Math.round(v * 10) / 10).toFixed(1);

const data = {
  params: PARAMS,
  hist: HIST,
  stats: {
    mean: round2(mean),
    median: round2(median),
    p5: round2(p5),
    var95: round2(var95),
    var95Pct: round2((var95 / PARAMS.S0) * 100),
    probLoss: round2(probLoss * 100),
    min: round2(Math.min(...terminals)),
    max: round2(Math.max(...terminals)),
    clampedIntoEdgeBins: hist.clamped,
    theoreticalMean: round2(PARAMS.S0 * Math.exp(PARAMS.mu * PARAMS.years)),
  },
  // Exact strings rendered on screen (rounded from the unrounded statistics).
  display: {
    S0: String(PARAMS.S0),
    runs: PARAMS.nRuns.toLocaleString("en-US"),
    mean: fmt1(mean),
    p5: fmt1(p5),
    var95Pct: fmt1((var95 / PARAMS.S0) * 100),
  },
  bins: hist.bins,
  terminals: terminals.map(round2),
  // Visible paths: full 253-point daily resolution, 2 dp (plenty at 1080px).
  paths: paths.slice(0, PARAMS.nVisible).map((p) => Array.from(p, round2)),
};

writeFileSync(
  join(assets, "sim-data.js"),
  `// GENERATED by build/simulate.mjs — do not edit.\nwindow.MC_SIM = ${JSON.stringify(data)};\n`,
);
const { paths: _p, terminals: _t, ...summary } = data;
writeFileSync(join(assets, "sim.json"), JSON.stringify(summary, null, 2) + "\n");

console.log(JSON.stringify({ stats: data.stats, display: data.display }, null, 2));
